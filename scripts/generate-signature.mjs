const word = "howlslab";
const strokes = [];
let x = 0;
for (const ch of word) {
  const [advance, d] = glyphs[ch];
  for (const part of d.split("M").map((s) => s.trim()).filter(Boolean)) {
    const nums = part.replace(/L/g, " ").trim().split(/\s+/).map(Number);
    const pts = [];
    for (let i = 0; i < nums.length; i += 2) pts.push([nums[i] + x, -nums[i + 1]]);
    strokes.push(pts);
  }
  x += advance * 0.97; // a hair tighter than the font's advance — reads more like a pen.
}

const all = strokes.flat();
const minX = Math.min(...all.map((p) => p[0]));
const minY = Math.min(...all.map((p) => p[1]));
const scale = 0.1;
const pad = 6;
const norm = strokes.map((pts) => pts.map(([px, py]) => [(px - minX) * scale + pad, (py - minY) * scale + pad]));
const width = Math.max(...norm.flat().map((p) => p[0])) + pad;
const height = Math.max(...norm.flat().map((p) => p[1])) + pad;

const f = (n) => Number(n.toFixed(1));
function catmullRom(pts) {
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i += 1) {
    const p0 = pts[i - 1] ?? pts[i];
    const p1 = pts[i];
    const p2 = pts[i + 1];
    const p3 = pts[i + 2] ?? p2;
    const t = 1 / 6;
    const c1 = [p1[0] + (p2[0] - p0[0]) * t, p1[1] + (p2[1] - p0[1]) * t];
    const c2 = [p2[0] - (p3[0] - p1[0]) * t, p2[1] - (p3[1] - p1[1]) * t];
    d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return d;
}

// Merge strokes whose ends touch (letters that join) so the pen keeps moving.
const merged = [];
for (const pts of norm) {
  const last = merged.at(-1);
  if (last) {
    const end = last.at(-1);
    const dist = Math.hypot(end[0] - pts[0][0], end[1] - pts[0][1]);
    if (dist < 7) {
      last.push(...pts.slice(dist < 0.5 ? 1 : 0));
      continue;
    }
  }
  merged.push([...pts]);
}

const d = merged.map(catmullRom).join("");
const out = `// Generated by scripts/generate-signature.mjs — do not edit by hand.
// Letterforms derived from EMS Allure / Allura (SIL Open Font License 1.1).
export const SIGNATURE_VIEWBOX = "0 0 ${f(width)} ${f(height)}";
export const SIGNATURE_PATH =
  "${d}";
`;
fs.writeFileSync(path.join(process.cwd(), "components", "signature-path.ts"), out);
console.log(`signature: ${merged.length} strokes, viewBox ${f(width)}×${f(height)}`);
